#!/usr/bin/env node
// Turns the Vbee narration timeline into src/scenes/vs_times.js (scene windows + per-word times, in seconds), so every
// shot can be cut to the real audio and key actions can land on the word that names them.
//   node viet-su/build-times.mjs <path to narration-expressive/timeline.json>
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DIR = dirname(fileURLToPath(import.meta.url));
const timeline = JSON.parse(readFileSync(process.argv[2], "utf8"));
const rows = readFileSync(join(DIR, "scenes.md"), "utf8").split("\n").filter((l) => l && !l.startsWith("#"));
const narrations = rows.map((l) => l.split(" | "));
if (narrations.length !== timeline.scenes.length) throw new Error("scene count differs from the timeline");

let w = 0;
const scenes = narrations.map(([id, text], i) => {
  const n = text.trim().split(/\s+/).length, start = timeline.scenes[i].startMs / 1000, end = timeline.scenes[i].endMs / 1000;
  const words = timeline.words.slice(w, w + n).map((x) => [x.text.trim().toLowerCase().replace(/[.,:;?!"“”]/g, ""), +(x.startMs / 1000 - start).toFixed(2), +(x.endMs / 1000 - start).toFixed(2)]);
  w += n;
  return { id: id.trim(), start: +start.toFixed(2), end: +end.toFixed(2), words };
});
if (w !== timeline.words.length) throw new Error(`consumed ${w} of ${timeline.words.length} words`);

const total = +(timeline.durationMs / 1000 + 0.6).toFixed(2);
writeFileSync(join(DIR, "../src/scenes/vs_times.js"),
  `// vs_times.js: generated by viet-su/build-times.mjs from the Vbee timeline. Do not edit by hand.\nconst VS_TIMES = ${JSON.stringify(scenes)};\nconst VS_TOTAL = ${total};\n`);
writeFileSync(join(DIR, "../src/config-vietsu.js"),
  `// config-vietsu.js: settings for the Việt sử video (vietsu.html); duration = narration length plus a short tail.\nconst PROJECT = { duration: ${total}, bpm: 90, offset: 0 };\n`);
console.log(`${scenes.length} scenes, total ${total}s`);
